import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../../', import.meta.url))
const run = (command, input = '', env = {}) =>
  spawnSync(process.execPath, ['deploy/scripts/config-tools.mjs', command], {
    cwd: root,
    input,
    encoding: 'utf8',
    env: { ...process.env, ...env },
  })
test('portable version selection handles minor versions numerically', () => {
  assert.equal(run('latest-version', '1.9\t1.32\n1.31').stdout, '1.32')
})
test('portable hashing and base64 decoding', () => {
  assert.match(
    run('hash', 'abc').stdout,
    /^ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad/,
  )
  assert.equal(run('decode', 'aHR0cHM6Ly9leGFtcGxlLmNvbQ==').stdout, 'https://example.com')
})
test('production overrides preserve other configuration and reject invalid input', () => {
  const config = JSON.stringify({ data: { COOKIE_SECURE: 'true', USER_API_TIMEOUT: '5000' } })
  const result = run('config', config, { USER_API_TIMEOUT: '8000' })
  assert.equal(result.status, 0, result.stderr)
  assert.deepEqual(JSON.parse(result.stdout).data, {
    COOKIE_SECURE: 'true',
    USER_API_TIMEOUT: '8000',
  })
  assert.notEqual(run('config', config, { USER_API_TIMEOUT: '-1' }).status, 0)
  assert.notEqual(run('config', config, { SUPPLIER_TIMEZONE: 'invalid-zone' }).status, 0)
})
test('service token references match generated resources and local bootstrap', () => {
  const read = (path) => readFileSync(`${root}/${path}`, 'utf8')
  assert.doesNotMatch(read('k8s/base/configmap.yaml'), /_TOKEN:/)
  const workloads = read('k8s/base/workloads.yaml')
  const local = read('floci/eks/up.sh')
  for (const key of new Set(
    [...workloads.matchAll(/name: relay-service-tokens, key: (\w+)/g)].map((m) => m[1]),
  )) {
    assert.ok(local.includes(`--from-literal=${key}=`), key)
    assert.ok(read('deploy/scripts/deploy-eks.sh').includes(`--from-literal=${key}=`), key)
  }
  for (const name of ['User', 'Supplier', 'Credit', 'Estimation']) {
    assert.ok(read('infra/relay-eks.yaml').includes(`${name}ServiceTokenArn:`))
  }
})
test('deployment scripts parse with system Bash', () => {
  for (const script of [
    'deploy/deploy.sh',
    'deploy/scripts/deploy-eks.sh',
    'deploy/scripts/aws-lifecycle-lib.sh',
    'floci/eks/up.sh',
  ]) {
    const result = spawnSync('/bin/bash', ['-n', script], { cwd: root, encoding: 'utf8' })
    assert.equal(result.status, 0, result.stderr)
  }
})
test('token provisioning rejects missing secrets and detects updates under system Bash', () => {
  const script = readFileSync(`${root}/deploy/scripts/deploy-eks.sh`, 'utf8')
  const block = script
    .split('# Secrets are generated by CloudFormation and never persisted in the env file.\n')[1]
    .split('step "Check Kafka topic initialization"')[0]
  const exercise = (secret, applyResult) =>
    spawnSync(
      '/bin/bash',
      [
        '-c',
        `
    set -euo pipefail
    secret_value() { printf '%s' "$TEST_TOKEN"; }
    kubectl() {
      case "$*" in
        *' get secret '*) return 0 ;;
        *' create secret '*) printf 'mock manifest' ;;
        'apply '*) cat >/dev/null; printf '%s' "$TEST_APPLY" ;;
        *) return 1 ;;
      esac
    }
    ${block}
    printf '%s' "$tokens_changed"
  `,
      ],
      {
        cwd: root,
        encoding: 'utf8',
        env: { ...process.env, TEST_TOKEN: secret, TEST_APPLY: applyResult },
      },
    )
  assert.notEqual(exercise('', 'configured').status, 0)
  assert.notEqual(exercise('local-internal-user-service-token', 'configured').status, 0)
  const changed = exercise('a'.repeat(48), 'secret/relay-service-tokens configured')
  assert.equal(changed.status, 0, changed.stderr)
  assert.equal(changed.stdout, '1')
  assert.equal(exercise('a'.repeat(48), 'secret/relay-service-tokens unchanged').stdout, '0')
})
test('production ECR publishing preserves the Docker endpoint with a temporary config', () => {
  const script = readFileSync(`${root}/deploy/scripts/deploy-eks.sh`, 'utf8')
  const lines = script.split('\n').map((line) => line.trim())
  const endpoint = lines.find((line) => line.startsWith('docker_endpoint='))
  const login = lines.find((line) => line.startsWith('docker --host') && line.includes(' login '))
  const push = lines
    .find((line) => line.startsWith('docker --host') && line.includes(' push '))
    ?.replace(' >&2 || return 1', '')
  assert.ok(endpoint && login && push, 'endpoint capture and both explicit-host operations exist')
  for (const host of ['', 'tcp://docker-engine:2375']) {
    const result = spawnSync(
      '/bin/bash',
      [
        '-c',
        `
      set -euo pipefail
      docker() {
        if [[ "$1" == context ]]; then
          printf '%s' 'unix:///tmp/docker-desktop.sock'
        else
          [[ "$1" == --host && "$2" == "$expected" && "$3" == --config && "$4" == "$ecr_docker_config" ]]
          cat >/dev/null
        fi
      }
      expected="\${DOCKER_HOST:-unix:///tmp/docker-desktop.sock}"
      ${endpoint}
      ecr_docker_config=/tmp/private-ecr-config
      registry=registry.example
      image_uri=registry.example/relay/host:latest
      printf '%s' mock-token | ${login}
      ${push}
    `,
      ],
      { cwd: root, encoding: 'utf8', env: { ...process.env, DOCKER_HOST: host } },
    )
    assert.equal(result.status, 0, result.stderr)
  }
})
